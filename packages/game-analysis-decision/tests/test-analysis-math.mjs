import assert from 'node:assert/strict';
import {capacity,responseWindow,proportions,continueValue} from '../scripts/analysis-math.mjs';
const demands=[{id:'food',demand_per_period:16,yield_per_unit_period:2},{id:'fuel',demand_per_period:18,yield_per_unit_period:3}];
assert.equal(capacity({capacity:12,shared:true,demands}).required_units,14);
assert.equal(capacity({capacity:12,shared:true,demands}).feasible,false);
assert.equal(capacity({capacity:12,shared:false,demands}).feasible,true);
assert.equal(capacity({capacity:14,shared:true,demands}).feasible,true);
assert.throws(()=>capacity({capacity:12,demands}),/shared/);
assert.throws(()=>capacity({capacity:12,shared:true,demands:[{...demands[0],yield_per_unit_period:0}]}),/yield/);
assert.equal(responseWindow({first_visible_ms:100,impact_ms:350,input_and_action_ms:250}).decision_window_ms,0);
assert.equal(responseWindow({first_visible_ms:100,impact_ms:300,input_and_action_ms:250}).decision_window_ms,-50);
assert.throws(()=>responseWindow({first_visible_ms:350,impact_ms:100,input_and_action_ms:0}),/precedes/);
const p=proportions({strata:[{id:'novice',wins:9,trials:10},{id:'experienced',wins:40,trials:100}]});
assert.equal(p.weighted_rate,49/110);
assert(Math.abs(p.rows[0].wilson95[0]-0.5958499732)<1e-8);
assert(Math.abs(p.rows[0].wilson95[1]-0.9821237869)<1e-8);
assert.throws(()=>proportions({strata:[{id:'bad',wins:11,trials:10}]}),/exceeds/);
assert.throws(()=>proportions({strata:[{id:'empty',wins:0,trials:0}]}),/trials/);
const v=continueValue({current_loot:10,additional_loot:3,failure_probability:0.2,retained_on_failure:0});
assert(Math.abs(v.delta_vs_safe_exit-0.4)<1e-12);
assert.equal(continueValue({current_loot:10,additional_loot:3,failure_probability:1,retained_on_failure:0}).delta_vs_safe_exit,-10);
assert.throws(()=>continueValue({current_loot:10,additional_loot:3,failure_probability:1.2,retained_on_failure:0}),/probability/);
assert.throws(()=>capacity({capacity:Infinity,shared:true,demands}),/finite/);
console.log('PASS: analysis math; capacity competition, timing, weighted sampling, expectation and invalid inputs. These calculations do not prove player experience.');
